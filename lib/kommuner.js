const k4 = (c) => String(c).padStart(4, '0');

export const nomKommune = (code) => KOMMUNE_NAMES[k4(code)] || null;
export const nomRegion = (code) => REGION_NAMES[String(code)] || null;
export const regionDeKommune = (code) => KOMMUNE_REGION[k4(code)] || null;

export function kommunerDeRegion(region) {
  const r = String(region);
  return Object.keys(KOMMUNE_REGION).filter((k) => KOMMUNE_REGION[k] === r);
}
